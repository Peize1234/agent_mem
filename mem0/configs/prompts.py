def _format_session_summary(summary):
    """Extract summary text from a string or dict with a 'summary' key."""
    if isinstance(summary, dict):
        return summary.get("summary", "")
    return summary or ""


def _serialize_memories(memories):
    """JSON-serialize a list of memory objects, defaulting to '[]'."""
    return json.dumps(memories or [], ensure_ascii=False, indent=2)


def _format_prompt_messages(messages):
    """Serialize messages using the role/content schema declared by the system prompt."""
    if isinstance(messages, str):
        return messages

    normalized_messages = []
    for message in messages or []:
        if not isinstance(message, dict):
            continue
        role = message.get("role")
        content = message.get("content")
        if role is None or content is None:
            continue
        normalized_messages.append({"role": role, "content": content})
    return json.dumps(normalized_messages, ensure_ascii=False, indent=2)


def _format_structured_prompt_section(title, content):
    """Fence complete JSON data so its model-visible indentation is also UI-visible."""
    try:
        parsed = json.loads(content)
    except (TypeError, json.JSONDecodeError):
        return f"## {title}\n{content}"
    if not isinstance(parsed, (dict, list)):
        return f"## {title}\n{content}"
    return f"## {title}\n```json\n{content}\n```"


def _resolve_observation_date(observation_date=None, new_messages=None):
    """Resolve the evicted messages' observation date, defaulting to today."""
    if observation_date is None and not isinstance(new_messages, str):
        observation_date = next(
            (
                message.get("created_at")
                for message in new_messages or []
                if isinstance(message, dict) and message.get("created_at")
            ),
            None,
        )
    if observation_date is None:
        return datetime.now(timezone.utc).date().isoformat()

    if isinstance(observation_date, datetime):
        return observation_date.date().isoformat()

    observation_date = str(observation_date)
    try:
        return datetime.fromisoformat(observation_date.replace("Z", "+00:00")).date().isoformat()
    except ValueError:
        return observation_date


def generate_additive_extraction_prompt(
    new_messages=None,
    session_summary=None,
    existing_long_term_memories=None,
    existing_related_memories=None,
    short_term_context=None,
    *,
    observation_date=None,
    custom_instructions=None,
    use_input_language=False,
):
    """Build the user prompt for additive (ADD-only) extraction with linking.

    Pairs with ADDITIVE_EXTRACTION_PROMPT system prompt.
    The LLM will produce only ADD operations, with optional linked_memory_ids.
    """
    observation_date = _resolve_observation_date(observation_date, new_messages)

    sections = []
    sections.append(_format_structured_prompt_section("新消息", _format_prompt_messages(new_messages)))
    sections.append(f"## 会话摘要\n{_format_session_summary(session_summary)}")
    sections.append(_format_structured_prompt_section("现有长期记忆", _serialize_memories(existing_long_term_memories)))
    sections.append(_format_structured_prompt_section("现有相关记忆", _serialize_memories(existing_related_memories)))
    sections.append(
        _format_structured_prompt_section("当前短期窗口上下文", _format_prompt_messages(short_term_context))
    )
    sections.append(f"## 观察日期\n{observation_date}")

    if custom_instructions:
        sections.append(f"## 自定义指令\n{custom_instructions}")

    if use_input_language:
        sections.append(
            "## 语言要求\n"
            "关键要求：使用与输入消息相同的语言和书写系统作答。\n"
            "1. 准确匹配用户消息的语言：用户使用韩语时用韩语提取，使用日语时用日语提取，依此类推。\n"
            "2. 保留输入所使用的准确文字和字母系统。\n"
            "3. 除非输入本身是英文，否则不要翻译或音译成英文。\n"
            "4. 无论使用何种语言，都要保持全部质量标准，包括上下文丰富和时间明确等。\n"
            "5. 技术术语、专有名词和品牌名应保持其在输入中的原始形式。\n"
            "6. 如果输入混合多种语言，例如 Hinglish，应同时保留混合语言风格和原书写系统。\n"
            "7. 对于日语，应利用对话上下文明确定省略的主语。\n"
            "8. 对于中日韩语言，应保持与原文相符的正式程度。"
        )

    sections.append("# 输出：")
    return "\n\n".join(sections)
